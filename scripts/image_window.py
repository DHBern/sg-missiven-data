"""Open or close a time-limited window in which the viewer shows our own copies
of page images that are not on the edition's IIIF server (letters the
Stadtarchiv has not published yet).

    python scripts/image_window.py open --from 2026-11-20 --until 2026-11-26
    python scripts/image_window.py close

``open`` writes two files:

* ``site/config.json``: the viewer shows the copies while the visitor's date
  lies within the window, and stops on its own afterwards;
* ``deploy/nginx/sg-missiven-images.conf``: the location on tei.dh.unibe.ch
  that serves them. It allows only the window's calendar days (server time)
  and answers 410 on every other day, so the images close even if nobody
  removes the snippet.

``close`` sets ``image_window`` to null and writes a snippet that always answers
410. Either way, the change reaches the public site through a commit to
``main``, and the nginx snippet through the steps in docs/IMAGE_WINDOW.md.
"""

from __future__ import annotations

import argparse
import datetime as dt
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BASE = "https://tei.dh.unibe.ch/sg-missiven-images/"
ALIAS = "/mnt/wbkolleg_dh_1/tei/datasets/sg-missiven-images/pages/"

HEAD = """# /etc/nginx/snippets/sg-missiven-images.conf — generated by scripts/image_window.py
# ({state}). Include it in the TLS server block of tei.dh.unibe.ch with one line:
#     include snippets/sg-missiven-images.conf;
# The images are 1500 px working copies of letters the Stadtarchiv St. Gallen has
# not published yet, on the research share (world-readable mount). Serve them only
# inside an agreed window; see docs/IMAGE_WINDOW.md in DHBern/sg-missiven-data.
"""


def snippet(days: list[str] | None) -> str:
    if not days:
        return HEAD.format(state="closed") + """
location ^~ /sg-missiven-images/ {
    return 410;
}
"""
    pattern = "|".join(days)
    return HEAD.format(state=f"open {days[0]} to {days[-1]}") + f"""
location ^~ /sg-missiven-images/ {{
    # only on these days (server time); every other day answers 410 Gone
    if ($time_iso8601 !~ "^({pattern})T") {{
        return 410;
    }}
    alias {ALIAS};
    add_header Access-Control-Allow-Origin "https://dhbern.github.io" always;
    add_header X-Robots-Tag "noindex, nofollow, noarchive" always;
    add_header Cache-Control "private, max-age=3600" always;
    autoindex off;
}}
"""


def main() -> None:
    ap = argparse.ArgumentParser()
    sub = ap.add_subparsers(dest="cmd", required=True)
    o = sub.add_parser("open")
    o.add_argument("--from", dest="start", required=True, help="YYYY-MM-DD, first day")
    o.add_argument("--until", required=True, help="YYYY-MM-DD, last day (inclusive)")
    o.add_argument("--base", default=BASE)
    sub.add_parser("close")
    args = ap.parse_args()

    cfg_path = ROOT / "site" / "config.json"
    cfg = json.loads(cfg_path.read_text(encoding="utf-8")) if cfg_path.exists() else {}
    out = ROOT / "deploy" / "nginx" / "sg-missiven-images.conf"
    out.parent.mkdir(parents=True, exist_ok=True)

    if args.cmd == "open":
        start = dt.date.fromisoformat(args.start)
        until = dt.date.fromisoformat(args.until)
        if until < start:
            raise SystemExit("--until is before --from")
        if (until - start).days > 31:
            raise SystemExit("a window longer than a month is not a window; ask the Stadtarchiv first")
        days = [(start + dt.timedelta(d)).isoformat() for d in range((until - start).days + 1)]
        cfg["image_window"] = {"base": args.base, "from": args.start, "until": args.until,
                               "note": "letters not yet published by the Stadtarchiv St. Gallen"}
        out.write_text(snippet(days), encoding="utf-8")
        print(f"open {args.start} – {args.until} ({len(days)} days)")
    else:
        cfg["image_window"] = None
        out.write_text(snippet(None), encoding="utf-8")
        print("closed")
    cfg_path.write_text(json.dumps(cfg, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"wrote {cfg_path.relative_to(ROOT)} and {out.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
